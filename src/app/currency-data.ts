/**
 * Format any USD amount into the target currency with appropriate symbols and compact formatting
 */
export function formatWithCurrency(
  usdAmount: number,
  currency: CurrencyInfo,
  compact = false,
  customDecimals?: number
): string {
  if (isNaN(usdAmount)) return `${currency.symbol}0`;

  const converted = usdAmount * currency.rate;
  const isSuffix = currency.symbolPosition === 'suffix';
  const sym = currency.symbol;

  if (compact) {
    if (Math.abs(converted) >= 1_000_000_000) {
      const val = (converted / 1_000_000_000).toFixed(2);
      return isSuffix ? `${val}B ${sym}` : `${sym}${val}B`;
    }
    if (Math.abs(converted) >= 1_000_000) {
      const val = (converted / 1_000_000).toFixed(2);
      return isSuffix ? `${val}M ${sym}` : `${sym}${val}M`;
    }
    if (Math.abs(converted) >= 1_000) {
      const val = (converted / 1_000).toFixed(0);
      return isSuffix ? `${val}K ${sym}` : `${sym}${val}K`;
    }
    const val = converted.toFixed(customDecimals ?? currency.decimals);
    return isSuffix ? `${val} ${sym}` : `${sym}${val}`;
  }

  const decs = customDecimals ?? currency.decimals;
  const formattedNum = new Intl.NumberFormat(currency.locale, {
    minimumFractionDigits: decs > 0 ? (decs === 0 ? 0 : 0) : 0,
    maximumFractionDigits: decs,
  }).format(Math.round(converted));

  return isSuffix ? `${formattedNum} ${sym}` : `${sym}${formattedNum}`;
}
